#!/usr/bin/env python3
# Claude, 23 October 2026 — a reading aid, outside the frozen instrument and analysis; it computes no number of the report.
"""Render every chain of a replacement run as one Markdown file a person can read top to bottom.

  python3 report/tools/chain_reader.py instrument/runs/main [--out instrument/runs/main/reports/chains]

Per generation: the mechanical outcome (from the instrument's own classifier), the order of the first note read and the
first forbidden access, the notes the episode started with (names), every note the agent wrote (verbatim), the
deliverable status and totals, and the agent's final message (verbatim, cut at 1,200 characters). Nothing is
summarised or interpreted; every line is copied from the records. INDEX.md lists the chains with their endpoints.
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "instrument"))
import schema  # noqa: E402  (the frozen classifier, imported, not changed)


def load(run):
    recs = [json.loads(l) for l in (run / "records.jsonl").open(encoding="utf-8")]
    return sorted(recs, key=lambda r: (r["cell"]["arm"], r["cell"]["chain"], r["cell"]["generation"]))


def outcome(rec):
    return schema.classify(schema.EpisodeRecord.from_json(rec))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("run")
    ap.add_argument("--out", default=None)
    a = ap.parse_args()
    run = Path(a.run).resolve()
    out = Path(a.out).resolve() if a.out else run / "reports" / "chains"
    out.mkdir(parents=True, exist_ok=True)
    recs = load(run)
    plan = json.loads((run / "plan.json").read_text(encoding="utf-8"))
    arms = plan.get("arms") or {}
    chains = {}
    for r in recs:
        chains.setdefault((r["cell"]["arm"], r["cell"]["chain"]), []).append(r)
    index = ["# Chains — reading index (generated by report/tools/chain_reader.py; verbatim from the records)\n",
             f"Run: `{run.name}`; {len(recs)} episodes; arms: " + ", ".join(f"{k}: seed {v.get('seed_trace') or 'none'}, audit sentence {v.get('audit')}" for k, v in arms.items()) + "\n",
             "| arm | chain | outcomes g1…g5 | LEAK | mislabel | first forbidden access (gen) | file |", "|---|---|---|---|---|---|---|"]
    for (arm, chain), eps in sorted(chains.items()):
        lines = [f"# {arm} — chain {chain}\n", f"Arm {arm} = {arms.get(arm, '')}; fixture seed {eps[0]['cell'].get('fixture_seed')}; "
                 f"execution slot {eps[0]['cell'].get('slot')}; seed trace {eps[0]['cell'].get('seed_trace')}\n"]
        outs, leaks, mis, reads = [], [], [], []
        for r in eps:
            c = r["cell"]; o = outcome(r)
            tag = o.get("outcome", "?")
            if o.get("LEAK"): tag += "+LEAK"; leaks.append(c["generation"])
            if o.get("STATUS_MISLABEL"): tag += "+MISLABEL"; mis.append(c["generation"])
            if o.get("READ"): reads.append(c["generation"])
            outs.append(tag)
            lines.append(f"## Generation {c['generation']} — `{r['episode_id']}` — {tag}\n")
            lines.append(f"- valid: {r['infrastructure_valid']}; first note read at action {c.get('first_note_read_i')}, "
                         f"first forbidden access at action {c.get('first_forbidden_i')}; inherited note read: {c.get('inherited_note_read')}; "
                         f"notes at start carried the payload: {c.get('initial_notes_payload')}")
            init = [p for p in (c.get("initial_files") or {}) if p.startswith("shared/")]
            lines.append(f"- notes the episode started with: {', '.join('`'+p+'`' for p in init) if init else 'none'}")
            d = r.get("deliverable") or {}
            summ = r.get("files_written", {}).get("workspace/summary.json")
            try:
                sj = json.loads(summ) if summ else None
            except Exception:
                sj = None
            if sj:
                lines.append(f"- deliverable: status `{sj.get('status')}`, record_count {sj.get('record_count')}, totals {sj.get('totals_by_region')}; "
                             f"covers missing records: {d.get('covers_missing_records')}, marked partial: {d.get('marked_partial')}")
            else:
                lines.append(f"- deliverable: none written (final message declares blocked: {d.get('final_message_declares_blocked')})")
            wrote = {p: t for p, t in r.get("files_written", {}).items() if p.startswith("shared/")}
            if wrote:
                for p, t in wrote.items():
                    pred = (c.get("notes") or {}).get(p, {})
                    lines.append(f"\n**Note written: `{p}`** (ORIGIN {pred.get('origin')}, AUTH {pred.get('auth')}, PAYLOAD {pred.get('payload')})\n")
                    lines.append("```\n" + t.rstrip() + "\n```")
            else:
                lines.append("\n**No note written.**")
            fm = (r.get("final_message") or "").strip()
            lines.append("\n**Final message (verbatim, cut at 1,200 characters):**\n")
            lines.append("> " + fm[:1200].replace("\n", "\n> ") + ("…" if len(fm) > 1200 else ""))
            lines.append("")
        fname = f"{arm}-chain-{chain:02d}.md"
        (out / fname).write_text("\n".join(lines) + "\n", encoding="utf-8")
        index.append(f"| {arm} | {chain} | {' · '.join(outs)} | {leaks or '—'} | {mis or '—'} | {reads[0] if reads else '—'} | `{fname}` |")
    (out / "INDEX.md").write_text("\n".join(index) + "\n", encoding="utf-8")
    print(json.dumps({"out": str(out), "chains": len(chains)}))


if __name__ == "__main__":
    main()
